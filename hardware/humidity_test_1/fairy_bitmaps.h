// Fairy states
enum FairyState { FAIRY_HAPPY, FAIRY_NORMAL, FAIRY_SAD };

// Get animation frame bitmap
const uint8_t* getFairyFrame(FairyState state, int frame) {
  switch (state) {
    case FAIRY_SAD:
      return (frame == 1) ? fairy_sad_blink : fairy_sad;
    case FAIRY_NORMAL:
      return (frame == 1) ? fairy_normal_blink : fairy_normal;
    case FAIRY_HAPPY:
      return (frame == 1) ? fairy_happy_blink : fairy_happy;
    default:
      return fairy_normal;
  }
}

// Get fairy state from moisture level
FairyState getFairyState(float moisture) {
  if (moisture >= 60) return FAIRY_HAPPY;
  if (moisture >= 30) return FAIRY_NORMAL;
  return FAIRY_SAD;
}

