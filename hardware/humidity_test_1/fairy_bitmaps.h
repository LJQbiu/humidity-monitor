// Animation frame index: 0=base, 1=blink, 2=wing flap
// State enum for fairy expressions
enum FairyState { FAIRY_DRY, FAIRY_SAD, FAIRY_NORMAL, FAIRY_HAPPY, FAIRY_WAVING, FAIRY_SURPRISED };

// Get fairy bitmap based on state, animation frame, and moisture
const uint8_t* getFairyFrame(FairyState state, int frame) {
  // frame: 0=base, 1=blink, 2=wing flap
  switch(state) {
    case FAIRY_DRY:
      return (frame==1) ? fairy_dry_blink : (frame==2) ? fairy_dry_flap : fairy_dry;
    case FAIRY_SAD:
      return (frame==1) ? fairy_sad_blink : (frame==2) ? fairy_sad_flap : fairy_sad;
    case FAIRY_NORMAL:
      return (frame==1) ? fairy_normal_blink : (frame==2) ? fairy_normal_flap : fairy_normal;
    case FAIRY_HAPPY:
      return (frame==1) ? fairy_happy_blink : (frame==2) ? fairy_happy_flap : fairy_happy;
    case FAIRY_WAVING:
      return (frame==1) ? fairy_waving_blink : (frame==2) ? fairy_waving_flap : fairy_waving;
    case FAIRY_SURPRISED:
      return (frame==1) ? fairy_surprised_blink : (frame==2) ? fairy_surprised_flap : fairy_surprised;
    default:
      return fairy_normal;
  }
}

// Get fairy state from moisture level
FairyState getFairyState(float moisture) {
  if (moisture >= 80) return FAIRY_HAPPY;
  if (moisture >= 60) return FAIRY_NORMAL;
  if (moisture >= 40) return FAIRY_SAD;
  if (moisture >= 20) return FAIRY_WAVING;
  return FAIRY_DRY;
}

